export function renderLeads(list) {
  const index = profiles.map(({ id, name }) => `<a href="#${id}">${name}</a>`).join('')
  const cards = profiles.map(({ id, name, role, badges, groups, romance, adultType, adult, image }) => `
    <article class="profile" id="${id}" aria-labelledby="${id}-name">
      <div class="profile-identity">
        ${image
          ? `<img class="profile-portrait" src="${image}" alt="${name} 프로필" width="400" height="600" loading="lazy">`
          : '<div class="profile-portrait profile-placeholder">프로필 사진 준비 중</div>'}
        <h2 id="${id}-name">${name}</h2>
        ${list(role + '.')}
        <ul class="profile-badges" aria-label="기본 정보">${badges.map(badge => `<li>${badge}</li>`).join('')}</ul>
      </div>
      <div class="profile-details">
        <div class="profile-facts">${groups.map(([title, lines]) => `<div><h3>${title}</h3>${list(...lines)}</div>`).join('')}</div>
        <div class="profile-relationship">
          <h3><span class="profile-rating">세이프</span> 연애</h3>
          ${list(...romance)}
          <details class="profile-adult">
            <summary><span class="profile-rating">19+ 언세이프</span> 성인 관계</summary>
            <span class="profile-rating profile-adult-type">${adultType}</span>
            ${list(...adult)}
          </details>
        </div>
      </div>
    </article>`).join('')
  return `<h1 class="profile-title">주연 캐릭터</h1><div class="profile-index" role="navigation" aria-label="인물 바로가기">${index}</div>${cards}`
}
