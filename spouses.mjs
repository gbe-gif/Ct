export function renderSpousePicker() {
  const cards = spouses.map(({ name, age, country, job, title, details }) => {
    const identity = `${age}세 남성·${country} 국적·${job}·(페소 이름)의 배우자`
    const lines = [identity, ...details]
    const note = ['# 추가 조연', `## ${name}`, ...lines.map(line => `- ${line}`)].join('\n')
    return `<details class="spouse-card">
      <summary><strong>${title}</strong><span class="spouse-identity">${name} · ${country} · ${age}세 · ${job}</span></summary>
      <ul>${details.map(line => `<li>${line}</li>`).join('')}</ul>
      <button type="button" class="spouse-action" data-copy-spouse>이 배우자 선택 · 복사</button>
      <textarea hidden readonly rows="8" aria-label="${name} 마크다운 유저노트">${note}</textarea>
      <p class="spouse-status" role="status"></p>
    </details>`
  }).join('')
  return `<div class="spouse-picker">
    <button type="button" class="spouse-action" id="open-spouses" aria-haspopup="dialog">내 쓰레기 배우자 고르기</button>
  </div>
  <dialog id="spouse-dialog" aria-labelledby="spouse-title">
    <div class="spouse-heading">
      <h2 id="spouse-title">내 쓰레기 배우자 고르기</h2>
      <form method="dialog"><button type="submit" autofocus>닫기</button></form>
    </div>
    <p>원하는 배우자 카드를 펼쳐 설정을 복사하세요. 유저노트에 붙여 넣은 뒤 <b>(페소 이름)</b>을 모두 대화프로필에 쓰는 이름으로 바꿔 주세요.</p>
    ${cards}
  </dialog>`
}
